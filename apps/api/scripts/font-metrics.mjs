// Generates src/render/font-metrics.ts: advance widths (in em) of the embedded fonts, used to fit
// labels without shipping a font parser in the worker. Run: node scripts/font-metrics.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const FONTS = { cinzelBold: 'Cinzel-Bold.ttf', alegreya: 'AlegreyaSC-Regular.ttf' }

function parse(buf) {
  const view = new DataView(buf.buffer, buf.byteOffset, buf.byteLength)
  const tables = {}
  const numTables = view.getUint16(4)
  for (let i = 0; i < numTables; i++) {
    const o = 12 + i * 16
    const tag = String.fromCharCode(...buf.subarray(o, o + 4))
    tables[tag] = view.getUint32(o + 8)
  }
  const unitsPerEm = view.getUint16(tables.head + 18)
  const numHMetrics = view.getUint16(tables.hhea + 34)
  const advance = (gid) => view.getUint16(tables.hmtx + 4 * Math.min(gid, numHMetrics - 1))

  // cmap format 4 (BMP)
  const cmap = tables.cmap
  const n = view.getUint16(cmap + 2)
  let sub = -1
  for (let i = 0; i < n; i++) {
    const pid = view.getUint16(cmap + 4 + i * 8)
    const eid = view.getUint16(cmap + 6 + i * 8)
    const off = view.getUint32(cmap + 8 + i * 8)
    if (view.getUint16(cmap + off) === 4 && (pid === 3 || pid === 0)) sub = cmap + off
    if (pid === 3 && eid === 1 && view.getUint16(cmap + off) === 4) break
  }
  const segX2 = view.getUint16(sub + 6)
  const ends = sub + 14
  const starts = ends + segX2 + 2
  const deltas = starts + segX2
  const rangeOffsets = deltas + segX2
  const glyph = (code) => {
    for (let s = 0; s < segX2 / 2; s++) {
      const end = view.getUint16(ends + 2 * s)
      if (code > end) continue
      const start = view.getUint16(starts + 2 * s)
      if (code < start) return 0
      const delta = view.getInt16(deltas + 2 * s)
      const ro = view.getUint16(rangeOffsets + 2 * s)
      if (!ro) return (code + delta) & 0xffff
      const g = view.getUint16(rangeOffsets + 2 * s + ro + 2 * (code - start))
      return g ? (g + delta) & 0xffff : 0
    }
    return 0
  }
  const widths = {}
  for (let code = 32; code < 0x250; code++) {
    const g = glyph(code)
    if (g) widths[String.fromCharCode(code)] = Math.round((advance(g) / unitsPerEm) * 1000) / 1000
  }
  return widths
}

let out = '// Generated by scripts/font-metrics.mjs — do not edit.\n'
out += '// Advance widths in em of the embedded fonts, for Latin characters.\n'
for (const [key, file] of Object.entries(FONTS)) {
  const widths = parse(readFileSync(new URL(`../assets/fonts/${file}`, import.meta.url)))
  out += `export const ${key}: Record<string, number> = ${JSON.stringify(widths)}\n`
}
writeFileSync(new URL('../src/render/font-metrics.ts', import.meta.url), out)
console.log('ok')
